/**
 * Server-side model gateway.
 *
 * - The platform owns model access; tenant API keys are never used. All provider
 *   secrets stay server-side (lib/config). 
 * - Supports a deterministic `mock` provider (no key, for local dev/test) and an
 *   `openai-compatible` provider (DeepSeek, OpenAI, …).
 * - Enforces request timeouts, bounded retries with exponential backoff, and
 *   returns token usage + cost so every call can be accounted for.
 */
import { config } from '../config'
import { GatewayError } from '../errors'

export interface ToolParameter {
  type: 'string' | 'number' | 'boolean'
  description?: string
  enum?: string[]
}
export interface ToolDef {
  name: string
  description: string
  parameters: Record<string, ToolParameter>
  required?: string[]
}
export interface ChatMessage {
  role: 'system' | 'user' | 'assistant' | 'tool'
  content: string
  toolCalls?: ToolCall[]
  toolCallId?: string
  name?: string
}
export interface ToolCall {
  id: string
  name: string
  arguments: Record<string, unknown>
}
export interface ModelRequest {
  model: string
  messages: ChatMessage[]
  tools?: ToolDef[]
  temperature?: number
  maxTokens?: number
}
export interface ModelResponse {
  content: string
  toolCalls: ToolCall[]
  tokensIn: number
  tokensOut: number
  costUsd: number
  model: string
  provider: string
}

export function estimateTokens(text: string): number {
  if (!text) return 0
  return Math.max(1, Math.round(text.length / 4))
}

// Documented fallback prices (USD per token) when the provider does not return
// cost. These are ESTIMATES, clearly distinct from provider-confirmed usage.
const FALLBACK_PRICE: Record<string, { in: number; out: number }> = {
  'deepseek-chat': { in: 0.00000027, out: 0.0000011 },
  'deepseek-reasoner': { in: 0.00000055, out: 0.0000022 },
  'gpt-4o-mini': { in: 0.00000015, out: 0.0000006 },
  'gpt-4o': { in: 0.0000025, out: 0.00001 },
}

export function computeCost(model: string, tokensIn: number, tokensOut: number): number {
  const override = config.model.costOverrides[model]
  const price = override ?? FALLBACK_PRICE[model] ?? FALLBACK_PRICE['deepseek-chat']
  return Number((tokensIn * price.in + tokensOut * price.out).toFixed(6))
}

// ---------------------------------------------------------------------------
// Mock provider: deterministic, no network. Produces a coherent, role-aware
// deliverable so local dev and tests see REAL persisted results, not stubs.
// ---------------------------------------------------------------------------
function mockDeliverable(req: ModelRequest): string {
  const lastUser = [...req.messages].reverse().find((m) => m.role === 'user')
  const userText = lastUser?.content ?? ''
  const system = req.messages.find((m) => m.role === 'system')?.content ?? ''
  const roleLine = system.match(/# Your identity\s*\n\s*You are ([^,]+),/)?.[1] ?? 'the assistant'
  const topic = userText.split('\n')[0].slice(0, 120)

  const now = new Date().toISOString().slice(0, 10)
  if (/research|analyst|competitor|summar/i.test(system + userText)) {
    return `# Research Brief — ${topic}\n\n_Prepared by ${roleLine.trim()} on ${now}._\n\n## Summary\nThis brief addresses: "${userText.trim()}". Key points are outlined below based on the supplied context.\n\n## Findings\n1. **Overview.** The request was reviewed against the available knowledge and prior context.\n2. **Comparison.** Where competitors or alternatives were named, differences were weighed on capability, cost, and fit.\n3. **Evidence.** Conclusions are grounded in the documents and context provided; nothing was invented.\n\n## Recommendations\n- Prioritize the option with the best fit for the stated goal.\n- Validate externally before committing resources.\n\n> Note: this result was produced by the offline mock provider. Configure MODEL_PROVIDER=openai-compatible with a real key for live model output.`
  }
  if (/market|social|content|campaign|copy/i.test(system + userText)) {
    return `# Marketing Draft — ${topic}\n\n_Prepared by ${roleLine.trim()} on ${now}._\n\n## Social Posts\n- Post 1: "${topic} — the upgrade your team didn't know it needed. #productivity"\n- Post 2: "We looked at the numbers so you don't have to. Here's what works. 📈"\n\n## Product Description\nA clear, benefit-led description derived from your brief, emphasizing outcomes over features.\n\n## Content Calendar (next 5 days)\n| Day | Theme | Asset |\n|-----|-------|-------|\n| 1 | Awareness | Launch post |\n| 2 | Education | How-to reel |\n| 3 | Social proof | Customer quote |\n| 4 | Offer | Promo |\n| 5 | Recap | Round-up |\n\n> Generated by the offline mock provider; set a real model for production copy.`
  }
  // Operations / default
  return `# Work Summary — ${topic}\n\n_Prepared by ${roleLine.trim()} on ${now}._\n\n## What I did\nI addressed: "${userText.trim()}".\n\n## Procedure\n1. Clarified the goal and constraints.\n2. Reviewed the relevant context and documents.\n3. Produced this structured result.\n\n## Next steps\n- Confirm the approach.\n- I can expand any section on request.\n\n> Produced by the offline mock provider.`
}

class MockProvider {
  async complete(req: ModelRequest): Promise<ModelResponse> {
    const content = mockDeliverable(req)
    const tokensIn = req.messages.reduce((a, m) => a + estimateTokens(m.content), 0)
    const tokensOut = estimateTokens(content)
    return {
      content,
      toolCalls: [],
      tokensIn,
      tokensOut,
      costUsd: computeCost(req.model || 'mock', tokensIn, tokensOut),
      model: req.model || 'mock',
      provider: 'mock',
    }
  }
}

// ---------------------------------------------------------------------------
// OpenAI-compatible provider (DeepSeek, OpenAI, …).
// ---------------------------------------------------------------------------
interface ProviderUsage { prompt_tokens?: number; completion_tokens?: number }
class OpenAICompatibleProvider {
  constructor(private baseUrl: string, private apiKey: string) {}

  async complete(req: ModelRequest, attempt = 0): Promise<ModelResponse> {
    const controller = new AbortController()
    const timeout = setTimeout(() => controller.abort(), config.model.requestTimeoutMs)
    try {
      const body: Record<string, unknown> = {
        model: req.model,
        messages: req.messages.map((m) => ({
          role: m.role,
          content: m.content,
          ...(m.toolCalls ? { tool_calls: m.toolCalls.map((t) => ({ id: t.id, type: 'function', function: { name: t.name, arguments: JSON.stringify(t.arguments) } })) } : {}),
          ...(m.role === 'tool' ? { tool_call_id: m.toolCallId, name: m.name } : {}),
        })),
        temperature: req.temperature ?? 0.3,
        max_tokens: req.maxTokens ?? 2048,
      }
      if (req.tools && req.tools.length > 0) {
        body.tools = req.tools.map((t) => ({
          type: 'function',
          function: { name: t.name, description: t.description, parameters: { type: 'object', properties: t.parameters, required: t.required ?? [] } },
        }))
      }
      const res = await fetch(`${this.baseUrl.replace(/\/$/, '')}/chat/completions`, {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${this.apiKey}` },
        body: JSON.stringify(body),
        signal: controller.signal,
      })
      if (res.status === 429 || res.status >= 500) {
        if (attempt < 3) {
          const backoff = Math.min(8000, 500 * 2 ** attempt) + Math.random() * 250
          await new Promise((r) => setTimeout(r, backoff))
          return this.complete(req, attempt + 1)
        }
        throw new GatewayError(`Model provider returned ${res.status}`)
      }
      if (!res.ok) {
        const text = await res.text().catch(() => '')
        throw new GatewayError(`Model provider error ${res.status}: ${text.slice(0, 300)}`)
      }
      const json = (await res.json()) as any
      const choice = json.choices?.[0]
      const msg = choice?.message ?? {}
      const usage: ProviderUsage = json.usage ?? {}
      const toolCalls: ToolCall[] = (msg.tool_calls ?? []).map((tc: any) => ({
        id: tc.id,
        name: tc.function?.name,
        arguments: safeParse(tc.function?.arguments),
      }))
      const tokensIn = usage.prompt_tokens ?? estimateTokens(JSON.stringify(req.messages))
      const tokensOut = usage.completion_tokens ?? estimateTokens(msg.content ?? '')
      const costUsd = computeCost(req.model, tokensIn, tokensOut)
      return {
        content: msg.content ?? '',
        toolCalls,
        tokensIn,
        tokensOut,
        costUsd,
        model: req.model,
        provider: 'openai-compatible',
      }
    } catch (err) {
      if (err instanceof GatewayError) throw err
      // Network/timeout errors: retry.
      if (attempt < 3) {
        const backoff = Math.min(8000, 500 * 2 ** attempt) + Math.random() * 250
        await new Promise((r) => setTimeout(r, backoff))
        return this.complete(req, attempt + 1)
      }
      throw new GatewayError(`Model request failed: ${(err as Error).message}`)
    } finally {
      clearTimeout(timeout)
    }
  }
}

function safeParse(s: unknown): Record<string, unknown> {
  if (typeof s === 'string') {
    try { return JSON.parse(s) } catch { return {} }
  }
  return (s as Record<string, unknown>) ?? {}
}

export type ModelGateway = { complete: (req: ModelRequest) => Promise<ModelResponse> }

let gatewayInstance: ModelGateway | null = null

export function getModelGateway(): ModelGateway {
  if (gatewayInstance) return gatewayInstance
  if (config.model.provider === 'mock' || !config.model.baseUrl) {
    gatewayInstance = new MockProvider()
  } else {
    gatewayInstance = new OpenAICompatibleProvider(config.model.baseUrl, config.model.apiKey)
  }
  return gatewayInstance
}

/** Reset cached gateway (tests). */
export function _resetGateway() {
  gatewayInstance = null
}
